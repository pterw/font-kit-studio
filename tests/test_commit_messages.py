BODY = 'Why the change was made.\n\n'


class ForbiddenFormTests(unittest.TestCase):
    def reasons(self, trailer):
        return check.check_message(f'feat: subject\n\n{BODY}{trailer}\n')

    def test_session_trailers_with_a_url_are_rejected(self):
        for trailer in ('Claude-Session: https://claude.ai/code/session_01abc',
                        'claude-session: https://example.com/x',
                        'Codex-Session: http://host/s/1',
                        'Agent-Session: claude.ai/code/session_1'):
            with self.subTest(trailer=trailer):
                self.assertEqual(len(self.reasons(trailer)), 1)
                self.assertIn('session', self.reasons(trailer)[0])

    def test_a_session_trailer_without_a_url_is_flagged_by_name_or_by_id(self):
        for trailer in ('Claude-Session: session_01WeZik6TnLLEfZRKbgPe4Y2',
                        'Agent-Session: session_abc123',
                        'Codex-Session: 7f3a',
                        'Review-Session: session_9'):
            with self.subTest(trailer=trailer):
                self.assertEqual(len(self.reasons(trailer)), 1)
                self.assertIn('session', self.reasons(trailer)[0])

    def test_an_ordinary_session_trailer_is_not_flagged(self):
        self.assertEqual(self.reasons('Review-Session: planning'), [])
        self.assertEqual(self.reasons('Training-Session: onboarding'), [])

