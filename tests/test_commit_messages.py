def git(repo, *args, message=None):
    env = dict(os.environ, GIT_AUTHOR_NAME='A', GIT_AUTHOR_EMAIL='a@example.com',
               GIT_COMMITTER_NAME='A', GIT_COMMITTER_EMAIL='a@example.com')
    return subprocess.run(['git', '-c', 'commit.gpgsign=false', *args], cwd=repo, env=env, check=True,
                          capture_output=True, text=True, input=message).stdout


class RangeTests(unittest.TestCase):
    def setUp(self):
        folder = tempfile.TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.repo = Path(folder.name)
        git(self.repo, 'init', '-q', '-b', 'main')

    def commit(self, message):
        git(self.repo, 'commit', '-q', '--allow-empty', '-F', '-', message=message)

    def run_main(self, *argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = check.main(['--repo', str(self.repo), *argv])
        return code, out.getvalue(), err.getvalue()

    def test_a_range_checks_every_commit_in_it_and_nothing_before_it(self):
        self.commit('chore: base\n\nBase commit.\n\nClaude-Session: https://claude.ai/s/old\n')  # outside the range
        git(self.repo, 'branch', 'base')
        self.commit('feat: one\n\nWhy one.\n')
        self.commit('fix: two\n\nWhy two.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n')
        self.commit('docs: three\n\nWhy three.\n\nCo-authored-by: Ada <ada@example.com>\n')
        self.commit('refactor: four\n\nWhy four.\n\nGenerated with [Claude Code](https://claude.ai/code)\n')
        commits = check.commits_in_range('base..HEAD', self.repo)
        self.assertEqual([c.subject for c in commits], ['refactor: four', 'docs: three', 'fix: two', 'feat: one'])
        code, out, _ = self.run_main('--range', 'base..HEAD')
        self.assertEqual(code, 1)
        lines = out.splitlines()
        fails = [line for line in lines if line.startswith('FAIL ')]
        self.assertEqual(len(fails), 2)
        self.assertRegex(fails[0], r'^FAIL [0-9a-f]{7,} refactor: four: AI generation banner')
        self.assertRegex(fails[1], r'^FAIL [0-9a-f]{7,} fix: two: AI assistant co-author')
        self.assertEqual(lines[-1], 'commit-message check: FAIL: 2 of 4 commits carry agent or process signatures')

    def test_a_clean_range_exits_zero_with_a_one_line_summary(self):
        self.commit('chore: base\n\nBase.\n')
        git(self.repo, 'branch', 'base')
        self.commit('feat: one\n\nWhy.\n\nCo-authored-by: Ada <ada@example.com>\n')
        self.commit('feat: two\n\nWhy.\n')
        code, out, _ = self.run_main('--range', 'base..HEAD')
        self.assertEqual((code, out), (0, 'commit-message check: OK: 2 commits checked\n'))

    def test_without_a_range_only_the_last_commit_is_checked(self):
        self.commit('chore: old\n\nGenerated by ChatGPT\n')
        self.commit('feat: new\n\nWhy.\n')
        code, out, _ = self.run_main()
        self.assertEqual((code, out), (0, 'commit-message check: OK: 1 commit checked\n'))
        self.commit('fix: newest\n\nWhy.\n\nClaude-Session: https://claude.ai/s/1\n')
        self.assertEqual(self.run_main()[0], 1)

    def test_an_all_zero_before_sha_from_a_new_branch_push_means_the_last_commit(self):
        self.commit('feat: one\n\nWhy.\n')
        zeros = '0' * 40
        code, out, _ = self.run_main('--range', f'{zeros}..HEAD')
        self.assertEqual((code, out), (0, 'commit-message check: OK: 1 commit checked\n'))

    def test_merge_commits_are_skipped(self):
        self.commit('chore: base\n\nBase.\n')
        git(self.repo, 'checkout', '-q', '-b', 'topic')
        self.commit('feat: topic\n\nWhy.\n')
        git(self.repo, 'checkout', '-q', 'main')
        self.commit('feat: main\n\nWhy.\n')
        git(self.repo, 'merge', '--no-ff', '-q', 'topic', '-m', 'Merge topic\n\nGenerated with Claude Code')
        commits = check.commits_in_range('HEAD~2..HEAD', self.repo)
        self.assertNotIn('Merge topic', [c.subject for c in commits])

    def test_base_checks_base_to_head_when_the_ref_exists_otherwise_the_last_commit(self):
        self.commit('chore: base\n\nBase.\n')
        git(self.repo, 'branch', 'base')
        self.commit('fix: bad\n\nWhy.\n\nClaude-Session: https://claude.ai/s/1\n')
        self.commit('feat: fine\n\nWhy.\n')
        code, out, _ = self.run_main('--base', 'base')
        self.assertEqual(code, 1, 'the range base..HEAD includes the bad commit, not only the last one')
        self.assertIn('fix: bad', out)
        code, out, _ = self.run_main('--base', 'origin/missing')
        self.assertEqual((code, out), (0, 'commit-message check: OK: 1 commit checked\n'))

    def test_base_that_is_head_checks_the_last_commit(self):
        self.commit('feat: one\n\nWhy.\n')
        self.assertEqual(self.run_main('--base', 'HEAD')[1], 'commit-message check: OK: 1 commit checked\n')

    def test_an_unreadable_range_is_an_error_not_a_pass(self):
        self.commit('feat: one\n\nWhy.\n')
        code, _, err = self.run_main('--range', 'nosuchbase..HEAD')
        self.assertEqual(code, 1)
        self.assertIn('commit-message check: ERROR', err)

    def test_log_parsing_keeps_multiline_messages_whole(self):
        text = (f'abc1234{check.FIELD}subject one{check.FIELD}subject one\n\nline a\nline b\n{check.RECORD}\n'
                f'def5678{check.FIELD}subject two{check.FIELD}subject two\n{check.RECORD}')
        commits = check.parse_log(text)
        self.assertEqual([(c.short_sha, c.subject) for c in commits], [('abc1234', 'subject one'), ('def5678', 'subject two')])
        self.assertIn('line b', commits[0].message)


